package com.servicedesk.dto;

import com.servicedesk.entity.Role;

/**
 * Returned after a successful register or login. The token is what the
 * client sends back in the Authorization header on later requests.
 */
public class AuthResponse {

    private String token;
    private Long userId;
    private String name;
    private String email;
    private Role role;

    public AuthResponse(String token, Long userId, String name, String email, Role role) {
        this.token = token;
        this.userId = userId;
        this.name = name;
        this.email = email;
        this.role = role;
    }

    public String getToken() {
        return token;
    }

    public Long getUserId() {
        return userId;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public Role getRole() {
        return role;
    }
}
